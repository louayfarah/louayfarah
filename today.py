"""
Refreshes the numbers on the profile card (dark_mode.svg, light_mode.svg): age, repositories, stars,
commits, followers and lines of code.

Based on https://github.com/Andrew6rant/Andrew6rant by Andrew Grant (2022-2025). Changed here:
- private and organisation repositories only add to the totals: their names are never written
  anywhere. The per-repository cache is keyed by a keyed hash, stays out of git (see .gitignore and
  the workflow), and error messages never include GitHub's response text;
- the age line is written to the card;
- repositories the token cannot read are skipped instead of stopping the run;
- only my own commits are fetched from each repository, and progress is saved after every repository;
- requests GitHub fails with a 502/503/504 are tried again;
- commits of more than MAX_COMMIT_LINES lines are left out of the lines-of-code total.
"""
