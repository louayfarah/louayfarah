# Classic token: scopes `repo`, `read:org`, `read:user` (private and organisation repositories included).
HEADERS = {'authorization': 'token '+ os.environ['ACCESS_TOKEN']}
USER_NAME = os.environ.get('USER_NAME', 'louayfarah')
BIRTHDAY = datetime.datetime(2003, 6, 7)
# A commit adding or deleting more lines than this is data, not code (generated files, datasets, vendored
# sources): it counts as a commit, but its lines are left out of the lines-of-code total.
MAX_COMMIT_LINES = 10_000
CACHE_DIR = 'cache'
QUERY_COUNT = {'user_getter': 0, 'follower_getter': 0, 'graph_repos_stars': 0, 'recursive_loc': 0, 'graph_commits': 0, 'loc_query': 0}


def daily_readme(birthday):
    """
    Returns the length of time since I was born
    e.g. 'XX years, XX months, XX days'
    """
    diff = relativedelta.relativedelta(datetime.datetime.today(), birthday)
    return '{} {}, {} {}, {} {}{}'.format(
        diff.years, 'year' + format_plural(diff.years), 
        diff.months, 'month' + format_plural(diff.months), 
        diff.days, 'day' + format_plural(diff.days),
        ' 🎂' if (diff.months == 0 and diff.days == 0) else '')


def format_plural(unit):
    """
    Returns a properly formatted number
    e.g.
    'day' + format_plural(diff.days) == 5
    >>> '5 days'
    'day' + format_plural(diff.days) == 1
    >>> '1 day'
    """
    return 's' if unit != 1 else ''


def repo_key(name_with_owner):
    """
    Identifies a repository in the cache without revealing its name: a hash keyed with the access token,
    so it cannot be matched against guessed names. A new token simply rebuilds the cache.
    """
    return hmac.new(os.environ['ACCESS_TOKEN'].encode('utf-8'), name_with_owner.encode('utf-8'), hashlib.sha256).hexdigest()


def cache_file():
    os.makedirs(CACHE_DIR, exist_ok=True)
    return CACHE_DIR + '/' + hashlib.sha256(USER_NAME.encode('utf-8')).hexdigest() + '.txt' # one file per user


def post(query, variables):
    """
    Sends a GraphQL request. GitHub now and then answers 502/503/504 when it is busy, so those are tried again.
    """
    for attempt in range(4):
        request = requests.post('https://api.github.com/graphql', json={'query': query, 'variables':variables}, headers=HEADERS)
        if request.status_code not in (502, 503, 504):
            break
        time.sleep(5 * (attempt + 1))
    return request


def simple_request(func_name, query, variables):
    """
    Returns a request, or raises an Exception if the response does not succeed.
    """
    request = post(query, variables)
    if request.status_code == 200:
        return request
    raise Exception(func_name, ' has failed with a', request.status_code, QUERY_COUNT)


